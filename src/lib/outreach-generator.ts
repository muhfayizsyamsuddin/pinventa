import type { Lead, OutreachDraft } from "@/types/pinventa";

const DRAFT_STORAGE_PREFIX = "pinventa:drafts:";

export function getDraftStorageKey(leadId: string): string {
  return `${DRAFT_STORAGE_PREFIX}${leadId}`;
}

export function loadDraftsForLead(leadId: string): OutreachDraft[] | null {
  if (typeof window === "undefined") return null;
  try {
    const raw = localStorage.getItem(getDraftStorageKey(leadId));
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
  } catch (err) {
    console.error("Failed to load drafts from localStorage:", err);
  }
  return null;
}

type DraftListener = () => void;
const listeners = new Set<DraftListener>();

export function subscribeDraftStore(listener: DraftListener): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function saveDraftsForLead(leadId: string, drafts: OutreachDraft[]): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(getDraftStorageKey(leadId), JSON.stringify(drafts));
    listeners.forEach((fn) => fn());
  } catch (err) {
    console.error("Failed to save drafts to localStorage:", err);
  }
}

