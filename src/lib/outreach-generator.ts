/**
 * Gets saved drafts for a lead from localStorage or initializes them with rule-based defaults.
 */
export function getOrInitDraftsForLead(
  lead: Lead,
  defaultDrafts?: OutreachDraft[],
): OutreachDraft[] {
  const saved = loadDraftsForLead(lead.id);
  if (saved && saved.length > 0) {
    return saved;
  }
  if (defaultDrafts && defaultDrafts.length > 0) {
    return defaultDrafts;
  }
  return generateLiveLeadDrafts(lead);
}
